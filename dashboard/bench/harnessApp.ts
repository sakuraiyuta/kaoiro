const LOBBY_TOPIC = "agents:lobby";
const BASE_TS_MS = Date.parse("2026-07-01T00:00:00Z");

interface Envelope {
  version: string;
  agent_id: string;
  persona: { id: string; name: string; sprite_set: string };
  ts: string;
  seq?: number;
  type: string;
  state: string;
  payload: Record<string, unknown>;
  ext?: Record<string, unknown>;
}

function tsFor(seq: number): string {
  return new Date(BASE_TS_MS + seq * 1000).toISOString();
}

// Long enough per entry to exercise the markdown renderer, mirroring
// bench/harness.ts's assistantLog (the #174/#304 hypothesis is about
// per-entry DOM weight, not a one-word stub).
function logText(seq: number): string {
  return (
    `## reply ${seq}\n\nこれはベンチ用の合成ログです。` +
    "段落を長めにして markdown レンダリングのコストを再現します。".repeat(3)
  );
}

function assistantLog(agentId: string, seq: number): Envelope {
  return {
    version: "0",
    agent_id: agentId,
    persona: { id: agentId, name: agentId, sprite_set: agentId },
    ts: tsFor(seq),
    seq,
    type: "log",
    state: "thinking",
    payload: { kind: "assistant", text: logText(seq) },
  };
}

// Terminal `result` entry, is_error optional — this is what
// latestErrorKeyByAgent (App.svelte) scans transcripts backwards for.
function resultLog(agentId: string, seq: number, isError: boolean): Envelope {
  return {
    version: "0",
    agent_id: agentId,
    persona: { id: agentId, name: agentId, sprite_set: agentId },
    ts: tsFor(seq),
    seq,
    type: "result",
    state: isError ? "error" : "done",
    payload: isError
      ? { is_error: true, error_detail: "bench synthetic failure" }
      : { is_error: false, text: "done" },
  };
}

// The agent's CURRENT state_change (what `agents[id]` / the snapshot
// carries) -- separate from its transcript history. `ext` here is where
// slash_commands / session_capabilities live (AgentDetail.svelte reads
// `envelope.ext?.slash_commands` directly with no isOperator gate on the
// client; #46's stripping is server-side only, so our fake "server" simply
// chooses to include it, unlike bench/harness.ts's `ext: {}`).
function stateEnvelope(
  agentId: string,
  seq: number,
  ext: Record<string, unknown> = {},
): Envelope {
  return {
    version: "0",
    agent_id: agentId,
    persona: { id: agentId, name: agentId, sprite_set: agentId },
    ts: tsFor(seq),
    seq,
    type: "state_change",
    state: "idle",
    payload: {},
    ext,
  };
}

interface AgentSeedConfig {
  agentId: string;
  historyCount: number;
  /** Append a `result`/is_error entry as the last history row (candidate A:
   *  "error あり/なし" — feeds latestErrorKeyByAgent). */
  withRecentError?: boolean;
  /** Merged into this agent's live state_change ext (slash_commands /
   *  session_capabilities for the harness validity fix, M1a/M1b). */
  ext?: Record<string, unknown>;
}

function buildHistory(cfg: AgentSeedConfig): Envelope[] {
  const rows: Envelope[] = [];
  for (let seq = 0; seq < cfg.historyCount; seq++) {
    rows.push(assistantLog(cfg.agentId, seq));
  }
  if (cfg.withRecentError) {
    rows.push(resultLog(cfg.agentId, cfg.historyCount, true));
  }
  return rows;
}

function getChannel(): FakeChannel {
  const socket = (window as unknown as { __fakeSocket?: Socket })
    .__fakeSocket;
  if (!socket) throw new Error("fake socket not constructed yet");
  const ch = socket._channelFor(LOBBY_TOPIC);
  if (!ch) throw new Error("lobby channel not joined yet");
  return ch;
}

// Public driver surface — Playwright's page.evaluate() calls these.
const bench = {
  /** Waits for the App to have opened its (fake) socket + joined the lobby
   *  channel, since connectKaoiro's join is async (a microtask in the fake,
   *  a real round-trip in production) relative to mount(). */
  async waitReady(): Promise<void> {
    for (let i = 0; i < 200; i++) {
      const socket = (window as unknown as { __fakeSocket?: Socket })
        .__fakeSocket;
      if (socket?._channelFor(LOBBY_TOPIC)?.joined) return;
      await new Promise((r) => setTimeout(r, 10));
    }
    throw new Error("timed out waiting for the fake channel to join");
  },

  /** Seeds N agents with their current state (snapshot) and per-agent
   *  transcript history, in one shot -- mirrors a real join's
   *  snapshot -> history push order. */
  seed(agents: AgentSeedConfig[]): void {
    const ch = getChannel();
    const snapshotAgents: Record<string, Envelope> = {};
    const historyAgents: Record<string, Envelope[]> = {};
    for (const cfg of agents) {
      snapshotAgents[cfg.agentId] = stateEnvelope(
        cfg.agentId,
        cfg.historyCount + 1000,
        cfg.ext,
      );
      historyAgents[cfg.agentId] = buildHistory(cfg);
    }
    ch._emit("snapshot", {
      version: "0",
      agents: snapshotAgents,
      snapshot_incomplete: false,
    });
    ch._emit("history", {
      version: "0",
      agents: historyAgents,
      history_incomplete: false,
    });
  },

  /** Live "receive tick": push one more log entry onto an agent's
   *  transcript (candidate A's traffic generator). `seq` must be unique and
   *  increasing per agent (dedup key includes seq) -- callers own a running
   *  counter per agentId. */
  sendLog(agentId: string, seq: number, isErrorResult = false): void {
    const ch = getChannel();
    ch._emit(
      "envelope",
      isErrorResult ? resultLog(agentId, seq, true) : assistantLog(agentId, seq),
    );
  },

  /** Live task envelope (candidate D: TaskRing dot count). */
  sendTask(
    agentId: string,
    taskId: string,
    kind: "started" | "updated" | "completed",
    seq: number,
  ): void {
    const ch = getChannel();
    ch._emit("envelope", {
      version: "0",
      agent_id: agentId,
      persona: { id: agentId, name: agentId, sprite_set: agentId },
      ts: tsFor(seq),
      seq,
      type: "task",
      state: "thinking",
      payload: {
        kind,
        agent_id: agentId,
        task_id: taskId,
        task_type: "bench-task",
        status: kind === "completed" ? "completed" : "running",
      },
    });
  },

  /** Same probe as bench/harness.ts: time from a composer keystroke to the
   *  next painted frame. Kept for continuity with the #174/round-0 metric
   *  (see the "old metric" comment on Event Timing below, in runBenchApp). */
  armLatencyProbe(): boolean {
    const textarea = document.querySelector("textarea");
    if (!textarea) return false;
    (window as unknown as { __latencies: number[] }).__latencies = [];
    textarea.addEventListener("input", () => {
      const start = performance.now();
      requestAnimationFrame(() => {
        (window as unknown as { __latencies: number[] }).__latencies.push(
          performance.now() - start,
        );
      });
    });
    return true;
  },
};

